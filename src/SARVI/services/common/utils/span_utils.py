@contextlib.contextmanager
def suppress_stderr():
    """
    Suppress stderr.

    Parameters
    ----------

    Returns
    -------
        `Any`
            - Derived value produced by the operation.
    """
    old_stderr = os.dup(2)
    devnull = os.open(os.devnull, os.O_WRONLY)
    try:
        os.dup2(devnull, 2)
        yield
    finally:
        os.dup2(old_stderr, 2)
        os.close(old_stderr)
        os.close(devnull)
